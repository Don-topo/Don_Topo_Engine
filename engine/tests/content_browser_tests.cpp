// GameObject with a SkinnedMesh (ModelLoader::loadSkinned) and a known texture path
// set by hand in materials[0] instead of the one the FBX brings: the
// goal of the following tests is to pin down the walk of materialsOf()
// (countSceneReferences/updateSceneReferencesForRename/
// detachSceneReferencesForDelete), not the specific content of the asset.
static std::unique_ptr<GameObject> makeSkinnedFixture(const std::string& texturePath)
{
    auto go = std::make_unique<GameObject>("Rigged");
    auto mesh = std::make_shared<SkinnedMesh>(ModelLoader::loadSkinned("assets/modelAnimation.fbx"));
    CHECK(!mesh->materials.empty());
    if (!mesh->materials.empty())
        mesh->materials[0].texturePath = texturePath;
    go->setMesh(mesh);
    return go;
}

// loadSkinned never populates the inherited Mesh::material (it hands out materials in
// SkinnedMesh::materials); looking only at material left this case returning
