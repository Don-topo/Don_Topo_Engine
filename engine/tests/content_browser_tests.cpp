// Creates a temporary tree with normal folders, noise to filter out and a
// loose file. Returns the root.
static fs::path makeFixture()
{
    std::error_code ec;
    fs::path root = fs::temp_directory_path(ec) / "dt_content_browser_test";
    fs::remove_all(root, ec);
    fs::create_directories(root / "assets", ec);
    fs::create_directories(root / "Scripts", ec);
    fs::create_directories(root / ".hidden", ec);
    fs::create_directories(root / "build-ninja", ec);
    fs::create_directories(root / "cmake-build-debug", ec); // CLion
    // Name that no list contemplates, but with the CMakeCache inside: it is the
    // criterion that really decides (x64-Debug is generated by Visual Studio).
    fs::create_directories(root / "x64-Debug", ec);
    std::ofstream(root / "x64-Debug" / "CMakeCache.txt") << "x";
    // Name that STARTS with "build" but is not a build tree: it is shown.
    fs::create_directories(root / "build_assets", ec);
    // Generic build folder name, but WITHOUT CMakeCache: here it is a
    // user assets folder and it has to be shown (see isHiddenDir).
    fs::create_directories(root / "out", ec);
    std::ofstream(root / "readme.txt") << "x";
    return root;
}

// Lists only subfolders: no files, no hidden ones, no build trees.
static void test_filters_noise(const fs::path& root)
{
    std::vector<fs::path> dirs = listVisibleSubdirs(root);
    CHECK(dirs.size() == 4);
    if (dirs.size() == 4) {
        // std::sort on paths: 'S' (83) goes before the lowercase letters.
        CHECK(dirs[0].filename() == "Scripts");
        CHECK(dirs[1].filename() == "assets");
        // Neither the "build" prefix nor the suffix hides it: it has no CMakeCache.
        CHECK(dirs[2].filename() == "build_assets");
        CHECK(dirs[3].filename() == "out");
    }
}

// A folder with a build name but without a CMakeCache inside belongs to the user and is
