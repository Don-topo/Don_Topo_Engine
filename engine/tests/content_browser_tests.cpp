// The rename had the same blind spot with GameObject::materialOverrides that it
// used to have with SkinnedMesh::materials: it rewrote the Material IN MEMORY
// but not the override, which is what really survives a save
// (mesh.materials, Task 6). Without this, the serialized override kept
// pointing to the old name and the next Load did not find the texture;
// silent data loss. The three slots at once: the guard has to
// cover albedo, normal and orm, not just the first one tested.
static void test_rename_rewrites_material_override_path()
{
    const std::string oldPath = "assets/knownTexture.png";
    const std::string newPath = "assets/renamedTexture.png";
    auto go = makeSkinnedFixture(oldPath);
    MaterialOverride ov;
    ov.index  = 0;
    ov.albedo = oldPath;
    ov.normal = oldPath;
    ov.orm    = oldPath;
    go->materialOverrides.push_back(ov);

    GameObject* selected = nullptr;
    bool isPlaying = false;
    EditorContext ctx{selected, isPlaying};
    updateSceneReferencesForRename(ctx, go.get(), oldPath, newPath, /*isDir=*/false);

    CHECK(go->materialOverrides[0].albedo == newPath);
    CHECK(go->materialOverrides[0].normal == newPath);
    CHECK(go->materialOverrides[0].orm    == newPath);
}

