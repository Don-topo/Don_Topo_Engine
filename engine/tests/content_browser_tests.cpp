// The baseline (base*) pointing to the file that was just deleted was not a
// cosmetic detail: with the override empty and the *Taken flag raised,
// applyMaterialOverrides takes the "go back to the baseline" branch and REWRITES that
// dead path into the Material. And the next applyMaterialOverrides could be
// the one from editing any OTHER slot, so it silently undid the
// replaceStaticTextureWithMissing that the delete had just done.
//
// The flag stays raised on purpose (checked below): it is what makes
// the reapplication leave the slot EMPTY instead of resurrecting the deleted
// file.
static void test_detach_clears_material_override_baseline()
{
    const std::string knownPath = "assets/knownTexture.png";
    auto go = makeSkinnedFixture(knownPath);
    MaterialOverride ov;
    ov.index           = 0;
    ov.baseAlbedo      = knownPath;   // the user already did Clear: empty override,
    ov.baseAlbedoTaken = true;        // baseline taken and pointing to the file
    ov.baseNormal      = knownPath;
    ov.baseNormalTaken = true;
    ov.baseOrm         = knownPath;
    ov.baseOrmTaken    = true;
    go->materialOverrides.push_back(ov);

    GameObject* selected = nullptr;
    bool isPlaying = false;
    EditorContext ctx{selected, isPlaying};
    detachSceneReferencesForDelete(ctx, go.get(), knownPath, /*isDir=*/false);

    CHECK(go->materialOverrides[0].baseAlbedo.empty());
    CHECK(go->materialOverrides[0].baseNormal.empty());
    CHECK(go->materialOverrides[0].baseOrm.empty());
    CHECK(go->materialOverrides[0].baseAlbedoTaken);

    // The proof that it mattered: reapplying now does NOT give the deleted
    // file back to the material. Before the fix, this line resurrected it.
    applyMaterialOverrides(*go);
    CHECK(go->getSkinnedMesh()->materials[0].texturePath.empty());
}

