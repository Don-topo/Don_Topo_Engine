static void test_apply_asset_click()
{
    const std::vector<fs::path> vis = { "a", "b", "c", "d", "e" };
    AssetSelection s;

    applyAssetClick(s, vis, "b", false, false);
    CHECK(selectionIs(s, {"b"}));
    CHECK(s.anchor && *s.anchor == fs::path("b"));

    applyAssetClick(s, vis, "d", true, false);          // Ctrl adds
    CHECK(selectionIs(s, {"b", "d"}));
    applyAssetClick(s, vis, "a", true, false);          // visible order, not click order
    CHECK(selectionIs(s, {"a", "b", "d"}));
    applyAssetClick(s, vis, "b", true, false);          // Ctrl on one already marked removes it
    CHECK(selectionIs(s, {"a", "d"}));
    CHECK(s.anchor && *s.anchor == fs::path("b"));      // the anchor is the last click

    applyAssetClick(s, vis, "c", false, false);         // a simple click replaces everything
    CHECK(selectionIs(s, {"c"}));
    applyAssetClick(s, vis, "e", false, true);          // Shift: range c..e
    CHECK(selectionIs(s, {"c", "d", "e"}));
    CHECK(s.anchor && *s.anchor == fs::path("c"));      // Shift does not move the anchor
    applyAssetClick(s, vis, "a", false, true);          // backward range: a..c
    CHECK(selectionIs(s, {"a", "b", "c"}));

    // Without an anchor, Shift behaves like a normal click.
    AssetSelection empty;
    applyAssetClick(empty, vis, "d", false, true);
    CHECK(selectionIs(empty, {"d"}));

    // Anchor that is no longer visible (a filter hid it): also a normal click.
    AssetSelection stale;
    stale.items  = { "z" };
    stale.anchor = fs::path("z");
    applyAssetClick(stale, vis, "c", false, true);
    CHECK(selectionIs(stale, {"c"}));
}

